def _normalize(text):
    return "".join(text.split())


def lookup_glossary(text, target):
    """命中术语库则返回精译，否则返回 None。
    先精确匹配，再做包含式模糊匹配（容忍 OCR 漏字/多字），最长键优先。"""
    norm = _normalize(text)
    entry = GLOSSARY.get(norm)
    if entry:
        return entry.get(target)
    if len(norm) < 3:
        return None
    best_key = None
    for key in GLOSSARY:
        if len(key) < 3:
            continue
        # 词条是 OCR 文本的子串（OCR 多出字符）
        hit = key in norm
        # OCR 文本是词条的子串（OCR 漏字），要求覆盖度 ≥70%，
        # 避免短标题片段命中长词条导致多个框展开成同一译文
        if not hit and norm in key and len(norm) >= len(key) * 0.7:
            hit = True
        if hit and (best_key is None or len(key) > len(best_key)):
            best_key = key
    if best_key:
        return GLOSSARY[best_key].get(target)
    # 字符相似度模糊匹配：容忍 OCR 单字误识（如 防摔->防择）
    if len(norm) >= 4:
        import difflib
        best_ratio, best_key2 = 0.7, None
        for key in GLOSSARY:
            if len(key) < 4:
                continue
            r = difflib.SequenceMatcher(None, norm, key).ratio()
            if r > best_ratio:
                best_ratio, best_key2 = r, key
        if best_key2:
            return GLOSSARY[best_key2].get(target)
    return None
